source('R/cache-guard.R')
must_fail <- function(expr) stopifnot(inherits(tryCatch({force(expr);NULL},error=identity),'error'))
f <- tempfile(); optional <- tempfile()
writeLines('original',f)
cache <- list(); attr(cache,'input_fingerprint') <- fingerprint_files(c(f,optional))
verify_prepared_ridership(cache)
writeLines('changed',f); must_fail(verify_prepared_ridership(cache))
writeLines('original',f); verify_prepared_ridership(cache)
writeLines('new independent crosscheck',optional); must_fail(verify_prepared_ridership(cache))
unlink(optional); unlink(f); must_fail(verify_prepared_ridership(cache))
must_fail(verify_prepared_ridership(list()))
cat('PASS: source change/deletion, new optional evidence and unversioned caches are rejected\n')
